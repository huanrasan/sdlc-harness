_HEADER_RE = re.compile(r"^\s*\[\[?\s*([^\]]+?)\s*\]\]?\s*(#.*)?$")
_KEY_RE = re.compile(r'^\s*("(?:[^"\\]|\\.)*"|[A-Za-z0-9_-]+)\s*=')


def _blocks(text: str) -> list[tuple[str | None, list[str]]]:
    """Split TOML text into (header path or None for the preamble, lines) blocks."""
    blocks: list[tuple[str | None, list[str]]] = [(None, [])]
    for line in text.splitlines():
        m = _HEADER_RE.match(line)
        if m:
            blocks.append((m.group(1), [line]))
        else:
            blocks[-1][1].append(line)
    return blocks


def _lookup(data: dict, dotted: str):
    node = data
    for part in re.findall(r'"[^"]*"|[^.]+', dotted):
        part = part.strip().strip('"')
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def merge_toml(current: str, template: str, label: str) -> tuple[str, list[str]]:
    """Add template tables and keys missing from `current`; never change existing values."""
    cur_data, tpl_data = tomllib.loads(current), tomllib.loads(template)
    notes: list[str] = []
    lines = current.splitlines()
    appended: list[str] = []
    for header, block in _blocks(template):
        if header is None or block[0].lstrip().startswith("[["):
            continue
        existing = _lookup(cur_data, header)
        if existing is None:
            body = list(block)
            while body and not body[-1].strip():
                body.pop()
            appended += ["", *body]
            notes.append(f"{label}: added [{header}]")
            continue
        if not isinstance(existing, dict):
            continue
        tpl_table = _lookup(tpl_data, header) or {}
        missing = [line for line in block[1:] if (m := _KEY_RE.match(line))
                   and m.group(1).strip('"') not in existing
                   and not isinstance(tpl_table.get(m.group(1).strip('"')), dict)]
        if not missing:
            continue
        idx = next(i for i, line in enumerate(lines) if (m := _HEADER_RE.match(line)) and m.group(1) == header)
        end = idx + 1
        while end < len(lines) and not _HEADER_RE.match(lines[end]):
            end += 1
        while end > idx + 1 and not lines[end - 1].strip():
            end -= 1
        for line in missing:
            if line.rstrip().endswith("[") or line.count("[") != line.count("]"):
                notes.append(f"{label}: new multi-line setting in [{header}] needs a manual merge: {line.strip()}")
                continue
            lines.insert(end, line)
            end += 1
            notes.append(f"{label}: added {header}.{_KEY_RE.match(line).group(1)}")
    result = "\n".join(lines + (["", f"# Added by sdlc upgrade {VERSION}"] + appended if appended else [])) + "\n"
    tomllib.loads(result)  # never write invalid TOML
    return result, notes


def upgrade(root: Path, dry_run: bool = False) -> int:
    if not (root / "harness.toml").exists():
        raise HarnessError("harness.toml not found; run `sdlc init` first")
    manifest = load_toml(root / MANIFEST) if (root / MANIFEST).exists() else {}
    base: dict[str, str] = manifest.get("files", {})
    report = Report()
    actions: list[str] = []
    new_manifest: dict[str, str] = {}
    writes: dict[Path, bytes] = {}
    deletes: list[Path] = []

    template = template_files(detect_ci(root))
    for rel, data in template.items():
        path, new_hash = root / rel, _digest(data, rel)
        if rel in MERGE_TOML and path.exists():
            merged, notes = merge_toml(path.read_text(encoding="utf-8"), data.decode("utf-8"), rel)
            if rel == "harness.toml":
                merged = re.sub(r'^version = ".*"$', f'version = "{VERSION}"', merged, count=1, flags=re.M)
            if merged != path.read_text(encoding="utf-8"):
                writes[path] = merged.encode("utf-8")
            actions += notes
            report.warnings += [n for n in notes if "manual merge" in n]
            continue
        if not path.exists():
            if rel in base:
                actions.append(f"kept deleted: {rel} (removed locally)")
                new_manifest[rel] = base[rel]
            else:
                writes[path] = data
                new_manifest[rel] = new_hash
                actions.append(f"added: {rel}")
            continue
        if rel in USER_OWNED:
            continue
        current = _digest(path.read_bytes(), rel)
        if current == new_hash:
            new_manifest[rel] = new_hash
        elif rel in base and current == base[rel]:
            writes[path] = data
            new_manifest[rel] = new_hash
            actions.append(f"updated: {rel}")
        elif rel in base and base[rel] == new_hash:
            new_manifest[rel] = base[rel]
        else:
            writes[path.with_name(path.name + ".sdlc-new")] = data
            if rel in base:
                new_manifest[rel] = base[rel]
            report.warn(f"customized: {rel} - new version written to {rel}.sdlc-new; merge it and delete the .sdlc-new file")

    for rel, old_hash in base.items():
        path = root / rel
        if rel in template or not path.exists():
            continue
        if _digest(path.read_bytes(), rel) == old_hash:
            deletes.append(path)
            actions.append(f"removed obsolete: {rel}")
        else:
            report.warn(f"obsolete but customized: {rel} (no longer shipped; review and delete)")
    legacy = root / ".harness" / "sdlc.py"
    if legacy.exists():
        deletes.append(legacy)
        actions.append("removed legacy: .harness/sdlc.py (replaced by .harness/sdlc.pyz)")

    for a in actions:
        print(a)
    if dry_run:
        print(f"dry run: {len(writes)} write(s), {len(deletes)} deletion(s); nothing changed")
        return report.print()
    for path, data in writes.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for path in deletes:
        path.unlink()
    _finish(root)
    _write_manifest(root, new_manifest)
    sync(root)
    print(f"upgraded to {manifest.get('version', 'unknown')} -> {VERSION}")
    return report.print()


def sync(root: Path) -> int:
    cfg = load_config(root)
    report, found = skills.check_skills(root, paths(cfg)["skills"])
    if report.errors:
        return report.print()
    if skills.write_index(root, found):
        print("updated AGENTS.md skills index")
    if (root / memory.MEMORY_DIR).is_dir():
        memory.write_index(root)
    adapters.sync(root, cfg)
    return 0
