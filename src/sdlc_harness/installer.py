MANIFEST = ".harness/manifest.toml"
# Configuration merged table by table: new tables and keys are added, existing values are never changed.
MERGE_TOML = {"harness.toml", ".harness/roster.toml"}
# Owned by the project after installation: created when missing, never overwritten.
USER_OWNED = {".harness/architecture.toml", ".harness/exceptions.toml", ".harness/deviations.toml",
              "docs/memory/INDEX.md", "docs/adr/README.md", "docs/changes/.gitkeep"}
ZIP_DATE = (1980, 1, 1, 0, 0, 0)


def _digest(data: bytes, rel: str = "") -> str:
    data = data.replace(b"\r\n", b"\n")
    if rel == "AGENTS.md":  # the generated skills index is not a customization
        data = skills.INDEX_RE.sub(skills.SKILLS_START + "\n" + skills.SKILLS_END, data.decode("utf-8")).encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def _walk(node, prefix: tuple[str, ...] = ()):
    for child in sorted(node.iterdir(), key=lambda c: c.name):
        if child.name == "__pycache__" or child.name.endswith(".pyc"):
            continue
        if child.is_dir():
            yield from _walk(child, prefix + (child.name,))
        else:
            yield "/".join(prefix + (child.name,)), child


def template_files(ci: str) -> dict[str, bytes]:
    """Template content as installed for a CI choice, keyed by repo-relative path (works from a zipapp too)."""
    root = resources.files("sdlc_harness") / "template"
    files = {}
    for rel, node in _walk(root):
        if rel.startswith("ci/"):
            continue
        if ci != "github" and rel.startswith(".github/workflows/"):
            continue
        files[rel] = node.read_bytes()
    if ci == "gitlab":
        files[".gitlab-ci.sdlc.yml"] = (root / "ci" / "gitlab" / ".gitlab-ci.sdlc.yml").read_bytes()
    return files


def build_pyz(target: Path, full: bool = False) -> None:
    """Deterministic stdlib zipapp of the package. `full` also bundles templates so the file can run `init`."""
    package = resources.files("sdlc_harness")
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("wb") as fh:
        fh.write(b"#!/usr/bin/env python3\n")
        with zipfile.ZipFile(fh, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            entries = [("__main__.py", b"import sys\nfrom sdlc_harness.cli import main\nsys.exit(main())\n")]
            entries += [(f"sdlc_harness/{rel}", node.read_bytes()) for rel, node in _walk(package)
                        if full or not rel.startswith("template/")]
            for name, data in sorted(entries):
                info = zipfile.ZipInfo(name, ZIP_DATE)
                info.external_attr = 0o644 << 16
                info.compress_type = zipfile.ZIP_DEFLATED
                zf.writestr(info, data)
    target.chmod(0o755)


def detect_ci(root: Path) -> str:
    if (root / ".gitlab-ci.sdlc.yml").exists():
        return "gitlab"
    return "github" if (root / ".github/workflows/sdlc-gates.yml").exists() else "none"


def _write_manifest(root: Path, files: dict[str, str]) -> None:
    lines = ["# Generated by sdlc init/upgrade: hashes of harness files as installed, used for 3-way upgrades.",
             f"version = {json.dumps(VERSION)}", "", "[files]"]
    lines += [f"{json.dumps(rel)} = {json.dumps(h)}" for rel, h in sorted(files.items())]
    (root / MANIFEST).write_text("\n".join(lines) + "\n", encoding="utf-8")


def _finish(root: Path) -> None:
    build_pyz(root / VENDORED_CLI)
    hooks = root / ".harness" / "hooks"
    for hook in hooks.iterdir() if hooks.is_dir() else []:
        hook.chmod(0o755)


def init(target: Path, profile: str, agents: list[str], mode: str, ci: str | None, adopt: bool = False) -> int:
    target.mkdir(parents=True, exist_ok=True)
    if ci is None:
        ci = "gitlab" if (target / ".gitlab-ci.yml").exists() else "github"
    detected = detect.detect(target) if adopt else None
    skipped, installed = [], {}
    for rel, data in template_files(ci).items():
        dst = target / rel
        if dst.exists():
            skipped.append(rel)
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)
        installed[rel] = _digest(data, rel)
    _finish(target)

    if "harness.toml" not in skipped:
        cfg_path = target / "harness.toml"
        text = cfg_path.read_text(encoding="utf-8")
        text = re.sub(r'^profile = ".*"$', f'profile = "{profile}"', text, flags=re.M)
        text = re.sub(r"^targets = \[.*\]$", "targets = [" + ", ".join(f'"{a}"' for a in agents) + "]", text, flags=re.M)
        text = re.sub(r'^mode = ".*"$', f'mode = "{mode}"', text, flags=re.M)
        cfg_path.write_text(text, encoding="utf-8")
    if ".harness/roster.toml" not in skipped and ci == "gitlab":
        roster = target / ".harness" / "roster.toml"
        roster.write_text(roster.read_text(encoding="utf-8").replace('platform = "github"', 'platform = "gitlab"'),
                          encoding="utf-8")
    if detected is not None:
        _apply_adoption(target, detected, profile, "AGENTS.md" in skipped)
    _write_manifest(target, installed)

    for s in skipped:
        print(f"skipped existing file: {s}")
    sync(target)
    print(
        "\nNext steps:\n"
        "  1. Edit .harness/roster.toml (people/teams per role), then: python3 .harness/sdlc.pyz codeowners\n"
        "  2. python3 .harness/sdlc.pyz hooks && python3 .harness/sdlc.pyz doctor\n"
        "  3. python3 .harness/sdlc.pyz new feature my-change --risk medium"
    )
    return 0


def _apply_adoption(target: Path, data: dict, profile: str, agents_md_existed: bool) -> None:
    agents_md = target / "AGENTS.md"
    text = agents_md.read_text(encoding="utf-8")
    if not agents_md_existed:
        agents_md.write_text(detect.fill_agents_md(text, data["commands"]), encoding="utf-8")
    elif detect.HARNESS_SECTION_START not in text:
        template = template_files("none")["AGENTS.md"].decode("utf-8")
        agents_md.write_text(text.rstrip() + "\n\n" + detect.harness_block(template), encoding="utf-8")
        print("appended harness sections to existing AGENTS.md")
    if data["contracts"]:
        cfg_path = target / "harness.toml"
        cfg_text = cfg_path.read_text(encoding="utf-8")
        cfg_text = re.sub(r"^(\[contracts\][^\[]*?)^files = \[\]$", lambda m: m.group(1) + f"files = {json.dumps(data['contracts'])}",
                          cfg_text, count=1, flags=re.M | re.S)
        cfg_path.write_text(cfg_text, encoding="utf-8")
    report = target / "docs" / "sdlc" / "adoption.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(detect.render_adoption(data, profile), encoding="utf-8")
    print("wrote docs/sdlc/adoption.md")


